static int gi(char c) {
    if (c >= 'A' && c <= 'Z') return c - 'A';
    if (c >= 'a' && c <= 'z') return c - 'a';
    if (c >= '0' && c <= '9') return 26 + (c - '0');
    switch (c) { case ':': return 36; case '.': return 37; case '-': return 38;
                 case '_': return 39; case '/': return 40; default: return 41; }
}

static inline uint32_t pack(Color c) {
    return ((uint32_t)c.a << 24) | ((uint32_t)c.r << 16) | ((uint32_t)c.g << 8) | c.b;
}

static inline void px(int x, int y, uint32_t p) {
    if (x < 0 || y < 0 || x >= SCREEN_W || y >= SCREEN_H) return;
    ((uint32_t *)g_fb[g_fb_idx])[y * (g_pitch / 4) + x] = p;
}

int gfx_init(void) {
    videoState st;
    if (videoGetState(0, 0, &st) != 0) return -1;
    if (videoGetResolution(st.displayMode.resolution, &g_vcfg) != 0) return -1;
    g_vcfg.aspect = VIDEO_ASPECT_16_9;
    if (videoConfigure(0, &g_vcfg, NULL, 0) != 0) return -1;
    g_pitch = g_vcfg.width * 4;
    for (int i = 0; i < 2; i++) {
        g_fb[i] = rsxMemalign(64, g_pitch * g_vcfg.height);
        memset(g_fb[i], 0, g_pitch * g_vcfg.height);
    }
    return 0;
}

void gfx_shutdown(void) { for (int i = 0; i < 2; i++) if (g_fb[i]) rsxFree(g_fb[i]); }
void gfx_begin(void) { }

void gfx_end(void) {
    gcmSetDisplayBuffer(g_fb_idx, (uint32_t)(uintptr_t)g_fb[g_fb_idx],
                        g_pitch, g_vcfg.width, g_vcfg.height);
    g_fb_idx ^= 1;
}

void gfx_clear(Color c) {
    uint32_t p = pack(c);
    int n = g_pitch * g_vcfg.height / 4;
    uint32_t *fb = (uint32_t *)g_fb[g_fb_idx];
    for (int i = 0; i < n; i++) fb[i] = p;
}

void gfx_rect(int x, int y, int w, int h, Color c) {
    uint32_t p = pack(c);
    for (int j = 0; j < h; j++) for (int i = 0; i < w; i++) px(x + i, y + j, p);
}

void gfx_text(int x, int y, const char *s, Color c, int sc) {
    uint32_t p = pack(c);
    int cx = x;
    for (const char *q = s; *q; q++) {
        int g = gi(*q);
        for (int r = 0; r < 7; r++) {
            uint8_t b = FONT[g][r];
            for (int col = 0; col < 5; col++)
                if (b & (1 << (4 - col)))
                    for (int sy = 0; sy < sc; sy++) for (int sx = 0; sx < sc; sx++)
                        px(cx + col * sc + sx, y + r * sc + sy, p);
        }
        cx += 6 * sc;
    }
}
